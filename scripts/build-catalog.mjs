import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { FLAGS } from "./flag-data.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "catalog-data.ts");
const ROUND = "circle-flags";
const SQUARED = "flag";
const SUBDIVISIONS = [
    "gb-eng",
    "gb-sct",
    "gb-wls",
    "gb-nir",
    "es-ct",
    "es-ga",
    "es-pv",
];

export const REGIONS = [
    ["africa", "Africa"],
    ["americas", "Americas"],
    ["asia", "Asia"],
    ["europe", "Europe"],
    ["oceania", "Oceania"],
    ["more", "More"],
];

const readPackage = (prefix, file) =>
    JSON.parse(
        readFileSync(
            join(ROOT, "node_modules", "@iconify-json", prefix, file),
            "utf8"
        )
    );

const served = (data, name) =>
    Object.hasOwn(data.icons, name) || Object.hasOwn(data.aliases ?? {}, name);

const inAllSets = (round, squared, code) =>
    served(round, code) &&
    served(squared, `${code}-4x3`) &&
    served(squared, `${code}-1x1`);

// circle-flags also draws language flags under two-letter names (en, ja…);
// only codes that flag-icons draws in both shapes are countries or regions.
export function candidates(round, squared) {
    return Object.keys({ ...round.icons, ...round.aliases })
        .filter(
            (name) => /^[a-z]{2}$/.test(name) || SUBDIVISIONS.includes(name)
        )
        .filter((code) => inAllSets(round, squared, code))
        .sort();
}

export function buildCatalog(round, squared, table, skip = ["xx"]) {
    const regionTitle = new Map(REGIONS);
    const missing = candidates(round, squared).filter(
        (code) => !skip.includes(code) && !Object.hasOwn(table, code)
    );
    if (missing.length > 0) {
        throw new Error(
            `scripts/flag-data.mjs has no entry for ${missing.join(", ")}`
        );
    }
    const dropped = [];
    const icons = [];
    for (const [code, row] of Object.entries(table)) {
        if (!inAllSets(round, squared, code)) {
            dropped.push(code);
            continue;
        }
        if (!regionTitle.has(row.region)) {
            throw new Error(`${code} has an unknown region ${row.region}`);
        }
        icons.push({
            name: code,
            title: row.title,
            keywords: [code, ...row.aliases, row.region].join(" "),
        });
    }
    icons.sort((a, b) => a.title.localeCompare(b.title, "en"));
    const categories = REGIONS.map(([id, title]) => ({
        id,
        title,
        names: icons
            .filter((icon) => table[icon.name].region === id)
            .map((icon) => icon.name),
    }));
    return { icons, categories, dropped };
}

function source(catalog) {
    const version = (prefix) => readPackage(prefix, "package.json").version;
    return (
        `// Generated by scripts/build-catalog.mjs from scripts/flag-data.mjs, @iconify-json/${ROUND} ${version(ROUND)} and @iconify-json/${SQUARED} ${version(SQUARED)}. Do not edit by hand.\n` +
        `import type { CatalogIcon, Category } from "./catalog";\n\n` +
        `export const ICONS: CatalogIcon[] = ${JSON.stringify(catalog.icons)};\n\n` +
        `export const CATEGORIES: Category[] = ${JSON.stringify(catalog.categories)};\n`
    );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const catalog = buildCatalog(
        readPackage(ROUND, "icons.json"),
        readPackage(SQUARED, "icons.json"),
        FLAGS
    );
    for (const code of catalog.dropped) {
        console.log(
            `note: ${code} is in flag-data.mjs but not drawn by every set; left out`
        );
    }
    const text = source(catalog);
    // Skipping identical writes keeps a second build from dirtying the tree.
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
        writeFileSync(OUT, text);
    }
}
